// Build deep-nlf/<book>-mem.js: memory aids (sound-alike hook, root link, picture sentence) + a Wikipedia thumbnail.
// usage: node tools/deep/build_mem.js <book a1|a2|b> <mem-out-dir>
const fs = require('fs'), path = require('path');
const [book, dir] = process.argv.slice(2);
const files = fs.readdirSync(dir).filter(f => f.startsWith(book + '-') && f.endsWith('.json')).sort();
const all = {};
for (const f of files) Object.assign(all, JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const titles = [...new Set(Object.values(all).map(c => c.t).filter(Boolean))];
const cachePath = path.join(dir, `thumbs-${book}.json`);
const cache = fs.existsSync(cachePath) ? JSON.parse(fs.readFileSync(cachePath, 'utf8')) : {};
const todo = titles.filter(t => !(t in cache));
(async () => {
  for (let i = 0; i < todo.length; i += 40) {
    const chunk = todo.slice(i, i + 40);
    const url = 'https://en.wikipedia.org/w/api.php?action=query&prop=pageimages%7Cpageprops&pithumbsize=330&ppprop=disambiguation&redirects=1&format=json&titles=' + encodeURIComponent(chunk.join('|'));
    let j = null;
    for (let tries = 0; tries < 6 && !j; tries++) {   // Wikipedia rate-limits: wait and retry
      if (tries) await new Promise(r => setTimeout(r, 4000 * tries));
      const res = await fetch(url, { headers: { 'User-Agent': 'dictation-site-build/1.0 (personal study project)' } });
      try { j = JSON.parse(await res.text()); } catch { console.error('rate limited, retrying…'); }
    }
    if (!j) throw new Error('Wikipedia kept refusing');
    const back = {};   // normalised / redirected title -> requested title
    for (const n of (j.query.normalized || [])) back[n.to] = back[n.from] || n.from;
    for (const r of (j.query.redirects || [])) back[r.to] = back[r.from] || r.from;
    for (const p of Object.values(j.query.pages || {})) {
      const req = back[p.title] || p.title;
      const ok = p.thumbnail && !(p.pageprops && 'disambiguation' in p.pageprops) && p.pageid > 0;
      cache[req] = ok ? { u: p.thumbnail.source.replace('thumb.wikimedia.org', 'upload.wikimedia.org').replace(/\?.*$/, ''), w: p.title.replace(/ /g, '_') } : null;
    }
    for (const t of chunk) if (!(t in cache)) cache[t] = null;
    fs.writeFileSync(cachePath, JSON.stringify(cache, null, 1));   // keep progress
    console.error(`thumbs ${Math.min(i + 40, todo.length)}/${todo.length}`);
    await new Promise(r => setTimeout(r, 1500));
  }
  fs.writeFileSync(cachePath, JSON.stringify(cache, null, 1));
  const out = {}; let withImg = 0;
  for (const [fr, c] of Object.entries(all)) {
    const im = c.t && cache[c.t]; if (im) withImg++;
    out[fr] = { ...(im ? { i: im } : {}), z: c.zh, e: c.en };
  }
  const body = Object.entries(out).map(([k, v]) => ` ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
  const dest = path.join(__dirname, '..', '..', 'deep-nlf', `${book}-mem.js`);
  fs.writeFileSync(dest, `// Memory aids + pictures for the NLF ${book.toUpperCase()} book. Generated by tools/deep/build_mem.js; pictures: Wikipedia (see each article).\nObject.assign(window.MEM = window.MEM || {}, {\n${body}\n});\n`);
  console.log(`${Object.keys(out).length} words, ${withImg} with a picture, ${titles.length - titles.filter(t => cache[t]).length} titles had no usable image`);
})();
